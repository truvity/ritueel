#!/usr/bin/env node
// site/public/_redirects, kept in step with site/published.txt.
//
//   gen-redirects.mjs            write the file
//   gen-redirects.mjs --check    exit 1 when the file is not what the script would write
//   gen-redirects.mjs --list     print the address of every file of docs/ that is not published
//   --root <dir>                 use another checkout (the tests do)
//
// The file has three parts.
//
// 1. The hand lines, outside the markers: `from to code`. A line whose target is a page of docs/
//    is kept up to date here. The target is published: `from <address> 301`. It is not: `from
//    <the file on GitHub> 302`, so an old address goes to its file in one step and not through
//    a chain. When the page is published again, the next run turns the line back to a 301.
//    A line whose target is not a page of docs/ (the status page) is kept. A line whose target
//    is a decision record is a link to its file on GitHub, because the records have no page.
// 2. The generated block between the markers: first, for each hand line whose source ends in a
//    slash, the same rule for the source without the slash (unless a hand line has it); then the
//    old addresses of the first eighteen decision records, read from site/old-records.txt: for
//    each, with and without the closing slash, a `301` in one hop to the old file at the commit
//    named there (a link to a fixed commit never changes, so the redirect is permanent); then one
//    `302` for the old address of every file of docs/ that is not published and has no hand line,
//    to the same file on GitHub, once with the closing slash and once without. The 302 is
//    deliberate: the page may come back.
//
// Cloudflare Workers static assets (https://developers.cloudflare.com/workers/static-assets/redirects/):
// 2000 static rules, 1000 characters a line, the first match wins, and a redirect is followed
// even where an asset exists, so a `from` must never be a published address.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  GITHUB_DOCS,
  OTHER_ADDRESSES,
  addressOf,
  docsFiles,
  fileOfPath,
  githubUrl,
  isPublished,
  isRecord,
  publishedDocs,
  repoRoot,
} from '../lib/published.mjs';

export const BEGIN = '# BEGIN generated by site/scripts/gen-redirects.mjs from site/published.txt: do not edit';
export const END = '# END generated';
export const OLD_RECORDS = 'site/old-records.txt';
const REPO_BLOB = 'https://github.com/truvity/ritueel/blob/';
const MAX_RULES = 2000;
const MAX_LINE = 1000;

// A file that is a page of docs/ at all: not a record (the records have no page; their old
// addresses come from site/old-records.txt), the decisions README or a file whose name starts
// with an underscore.
const isPageFile = (file) =>
  !isRecord(file) && !file.startsWith('decisions/') && !file.split('/').some((part) => part.startsWith('_'));

/** The docs files that are not published and have, or had, an address of their own. */
export function unpublishedFiles(root) {
  const published = new Set(publishedDocs(root));
  return docsFiles(root).filter((f) => isPageFile(f) && !published.has(f));
}

/** The file of docs/ that a redirect target names, as { file, fragment }, or undefined. */
function targetFile(to, root) {
  const hash = to.indexOf('#');
  const path = hash === -1 ? to : to.slice(0, hash);
  const fragment = hash === -1 ? '' : to.slice(hash);
  if (path.startsWith(GITHUB_DOCS)) {
    const file = path.slice(GITHUB_DOCS.length);
    if (!existsSync(join(root, 'docs', file))) {
      throw new Error(`_redirects: ${to} names ${file}, which is not a file of docs/`);
    }
    return { file, fragment };
  }
  if (path.startsWith('/')) {
    const file = fileOfPath(path, join(root, 'docs'));
    return file ? { file, fragment } : undefined;
  }
  return undefined;
}

/**
 * The rules for the old decision records: `{ sha, stems }` from site/old-records.txt, and the
 * rules (the address with and without its closing slash, to the old file at the commit, 301),
 * sorted. Throws on a bad sha, a file name that is not NNNN-kebab.md, a stem used twice.
 */
export function oldRecordRules(root) {
  const text = readFileSync(join(root, OLD_RECORDS), 'utf8');
  let sha;
  const stems = new Map();
  text.split('\n').forEach((raw, i) => {
    const line = raw.trim();
    if (line === '' || line.startsWith('#')) return;
    const at = `${OLD_RECORDS}:${i + 1}`;
    const commit = /^commit (\S+)$/.exec(line);
    if (commit) {
      if (sha) throw new Error(`${at}: a second commit line`);
      if (!/^[0-9a-f]{40}$/.test(commit[1])) throw new Error(`${at}: the commit must be 40 hex characters`);
      sha = commit[1];
      return;
    }
    const m = /^(\d{4}-[a-z0-9]+(?:-[a-z0-9]+)*) (\d{4}-[a-z0-9]+(?:-[a-z0-9]+)*\.md)$/.exec(line);
    if (!m) throw new Error(`${at}: not "<address stem> <NNNN-kebab-name.md>": ${line}`);
    if (stems.has(m[1])) throw new Error(`${at}: the address ${m[1]} is listed twice`);
    stems.set(m[1], m[2]);
  });
  if (!sha) throw new Error(`${OLD_RECORDS}: no "commit <sha>" line`);
  if (!stems.size) throw new Error(`${OLD_RECORDS}: no old address listed`);
  const rules = [...stems]
    .sort((a, b) => (a[0] < b[0] ? -1 : 1))
    .flatMap(([stem, file]) => {
      const to = `${REPO_BLOB}${sha}/docs/decisions/${file}`;
      return [`/decisions/${stem}/ ${to} 301`, `/decisions/${stem} ${to} 301`];
    });
  return { sha, stems, rules };
}

/** The new text of _redirects, from the current text. Throws on a rule that cannot be served. */
export function buildRedirects(root, current) {
  const lines = current.split('\n');
  const begin = lines.indexOf(BEGIN);
  const end = lines.indexOf(END);
  if ((begin === -1) !== (end === -1) || end < begin) throw new Error(`_redirects: the markers "${BEGIN}" and "${END}" must come as a pair, in that order`);
  // Everything outside the block, without the empty lines that end the file.
  const outside = begin === -1 ? lines : [...lines.slice(0, begin), ...lines.slice(end + 1)];
  while (outside.length && outside[outside.length - 1].trim() === '') outside.pop();

  const hand = [];
  const handFrom = new Set();
  const kept = outside.map((line) => {
    const text = line.trim();
    if (text === '' || text.startsWith('#')) return line;
    const [from, to, code, ...rest] = text.split(/\s+/);
    if (!from || !to || !code || rest.length) throw new Error(`_redirects: not "from to code": ${line}`);
    let out = `${from} ${to} ${code}`;
    const target = targetFile(to, root);
    if (target) {
      out = isPublished(target.file, root)
        ? `${from} ${addressOf(target.file)}${target.fragment} 301`
        : `${from} ${githubUrl(target.file)}${target.fragment} 302`;
    }
    handFrom.add(from);
    hand.push(out);
    return out;
  });

  // A hand line is written with the closing slash; Workers static assets match a rule on the exact
  // path and add the slash only to a path that has an asset, so the old address without the slash
  // would answer 404. The block repeats each rule for that form, so the hand lines stay as they are.
  const handNoSlash = hand.flatMap((rule) => {
    const [from, to, code] = rule.split(' ');
    return from.length > 1 && from.endsWith('/') && !handFrom.has(from.slice(0, -1))
      ? [`${from.slice(0, -1)} ${to} ${code}`]
      : [];
  });

  const generated = unpublishedFiles(root)
    .map((file) => ({ from: addressOf(file), file }))
    .filter(({ from }) => !handFrom.has(from))
    .sort((a, b) => (a.from < b.from ? -1 : a.from > b.from ? 1 : 0))
    // The address without its closing slash too: Workers static assets match a rule on the exact
    // path and add the slash only to a path that has an asset, so /guides/x would answer 404.
    .flatMap(({ from, file }) =>
      [from, ...(from.length > 1 && !handFrom.has(from.slice(0, -1)) ? [from.slice(0, -1)] : [])].map(
        (address) => `${address} ${githubUrl(file)} 302`,
      ),
    );

  const oldRecords = oldRecordRules(root).rules;
  const all = [...hand, ...handNoSlash, ...oldRecords, ...generated];
  const live = new Set([
    ...OTHER_ADDRESSES,
    ...docsFiles(root).filter((f) => isPublished(f, root)).map(addressOf),
  ]);
  const seen = new Set();
  for (const rule of all) {
    const from = rule.split(' ')[0];
    if (seen.has(from)) throw new Error(`_redirects: ${from} is the source of two rules`);
    seen.add(from);
    if (live.has(from)) throw new Error(`_redirects: ${from} is a published address; a redirect would shadow the page`);
    if (rule.length > MAX_LINE) throw new Error(`_redirects: a rule of ${rule.length} characters (the limit is ${MAX_LINE}): ${rule.slice(0, 80)}...`);
  }
  if (all.length > MAX_RULES) throw new Error(`_redirects: ${all.length} rules (the limit is ${MAX_RULES})`);

  return [...kept, '', BEGIN, ...handNoSlash, ...oldRecords, ...generated, END, ''].join('\n');
}

function main() {
  const args = process.argv.slice(2);
  const at = args.indexOf('--root');
  const root = at === -1 ? repoRoot() : args[at + 1];
  const file = join(root, 'site', 'public', '_redirects');
  if (args.includes('--list')) {
    for (const f of unpublishedFiles(root)) console.log(addressOf(f));
    return;
  }
  const current = readFileSync(file, 'utf8');
  const next = buildRedirects(root, current);
  if (args.includes('--check')) {
    if (next === current) return;
    const a = current.split('\n');
    const b = next.split('\n');
    let i = 0;
    while (i < a.length && i < b.length && a[i] === b[i]) i++;
    console.error(`gen-redirects: site/public/_redirects is not up to date, first difference at line ${i + 1}:`);
    console.error(`  has:  ${a[i] ?? '(end of file)'}`);
    console.error(`  want: ${b[i] ?? '(end of file)'}`);
    console.error('run just site-redirects');
    process.exit(1);
  }
  if (next !== current) writeFileSync(file, next);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (e) {
    console.error(String(e.message ?? e));
    process.exit(1);
  }
}
